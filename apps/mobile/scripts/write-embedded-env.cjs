/**
 * Bakes public runtime env into the JS bundle for release APKs.
 * Bare-workflow Constants.expoConfig.extra is often empty on device.
 */
require("dotenv").config({ path: ".env" });

const fs = require("fs");
const path = require("path");

const requireValues = process.argv.includes("--require");

const data = {
  supabaseUrl:
    process.env.NEXT_PUBLIC_SUPABASE_URL ??
    process.env.EXPO_PUBLIC_SUPABASE_URL ??
    "https://qqplffyjlpdhqwegbtea.supabase.co",
  supabaseAnonKey:
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ?? process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY ?? "",
  siteUrl:
    process.env.NEXT_PUBLIC_SITE_URL ??
    process.env.EXPO_PUBLIC_SITE_URL ??
    "https://www.taplite.store",
};

if (!data.supabaseAnonKey) {
  const msg =
    "Missing NEXT_PUBLIC_SUPABASE_ANON_KEY. Add it to apps/mobile/.env before building a release APK.";
  if (requireValues) {
    console.error(msg);
    process.exit(1);
  }
  console.warn(`write-embedded-env: ${msg}`);
}

const out = path.join(__dirname, "../src/config/embedded-env.generated.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Auto-generated by scripts/write-embedded-env.cjs — do not edit.\nexport const embeddedEnv = ${JSON.stringify(data, null, 2)} as const;\n`,
);
console.log("write-embedded-env: wrote src/config/embedded-env.generated.ts");
